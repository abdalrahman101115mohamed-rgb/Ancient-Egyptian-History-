// Helper to convert Arabic word to hieroglyphs
export function transliterateArabicToHieroglyphs(input: string): { glyphs: string; breakdown: { char: string; glyph: string; depiction: string }[] } {
  const normalized = input.trim().replace(/\s+/g, ' ');
  const breakdown: { char: string; glyph: string; depiction: string }[] = [];
  let glyphString = '';

  for (const ch of normalized) {
    if (ch === ' ') {
      glyphString += ' ';
      continue;
    }

    const match = HIEROGLYPH_ALPHABET.find(item => item.char.includes(ch));
    if (match) {
      glyphString += match.glyph;
      breakdown.push({
        char: ch,
        glyph: match.glyph,
        depiction: match.depictionAr,
      });
    } else {
      // default fallback to water wave or reed
      glyphString += '𓈖';
      breakdown.push({
        char: ch,
        glyph: '𓈖',
        depiction: 'موجة ماء (رمز بديل)',
      });
    }
  }

  return { glyphs: glyphString, breakdown };
}

