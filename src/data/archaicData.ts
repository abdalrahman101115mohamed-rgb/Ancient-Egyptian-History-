export interface Pharaoh {
  id: string;
  nameAr: string;
  nameEn: string;
  nameHieroglyphs: string;
  dynasty: number;
  period: string;
  reignDates: string;
  serekhMeaning: string;
  crown: 'white' | 'red' | 'double';
  tombLocation: string;
  achievements: string[];
  keyArtifacts: string[];
  bio: string;
  historicalSignificance: string;
}

export interface Artifact {
  id: string;
  titleAr: string;
  titleEn: string;
  period: string;
  dynasty: string;
  date: string;
  material: string;
  discoverySite: string;
  currentMuseum: string;
  description: string;
  details: string[];
  symbolism: string;
  glyphRepresentation?: string;
  category: 'palette' | 'macehead' | 'ivory' | 'statue' | 'stele' | 'vessel';
}

export interface MapSite {
  id: string;
  nameAr: string;
  nameEn: string;
  ancientName: string;
  region: 'Upper Egypt' | 'Lower Egypt' | 'Delta' | 'Oasis';
  regionAr: 'مصر العليا (الصعيد)' | 'مصر السفلى (الدلتا)' | 'الفيوم والواحات';
  latitudePct: number; // percentage from top on map (0 = north/delta, 100 = south/aswan)
  longitudePct: number; // percentage from left
  role: string;
  historicalImportance: string;
  keyDiscoveries: string[];
  associatedKings: string[];
}

export interface TimelinePeriod {
  id: string;
  nameAr: string;
  nameEn: string;
  dates: string;
  dynasties: string;
  isArchaicHighlight?: boolean;
  capitalAr: string;
  keyPharaohs: string[];
  majorMilestones: string[];
  summary: string;
}

export interface HieroglyphChar {
  char: string; // Arabic letter/sound
  latin: string; // Transliteration (e.g., ꜣ, b, p)
  glyph: string; // Unicode hieroglyph
  gardiner: string; // Gardiner sign list code (e.g., G1, D58)
  depictionAr: string; // What the sign depicts in Arabic
  depictionEn: string;
  phoneticDescription: string;
}

export interface QuizQuestion {
  id: number;
  question: string;
  options: string[];
  correctAnswer: number;
  explanation: string;
  dynastyContext: string;
}

